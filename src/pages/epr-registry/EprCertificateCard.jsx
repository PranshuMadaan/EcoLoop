import React from 'react';

export function EprCertificateCard({ cert, error, onCopyHash, copied }) {
  if (error) {
    return (
      <div className="p-6 rounded-3xl border border-rose-500/40 bg-gradient-to-br from-rose-950/20 to-slate-900 shadow-2xl text-white">
        <div className="flex items-center gap-3 text-rose-400 font-bold text-lg mb-2">
          <span>⚠️</span>
          <span>Ledger Verification Alert</span>
        </div>
        <p className="text-sm text-slate-300 mb-4">{error}</p>
        <div className="p-3.5 rounded-xl bg-slate-950/80 border border-white/10 text-xs font-mono text-slate-400">
          This cryptographic proof was not minted through an atomic Escrow auction settlement or was generated by an unaccredited facility without MoEFCC statutory clearance.
        </div>
      </div>
    );
  }

  if (!cert) return null;

  const dateFormatted = new Date(cert.issue_timestamp || Date.now()).toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
  const timeFormatted = new Date(cert.issue_timestamp || Date.now()).toLocaleTimeString('en-IN');

  return (
    <div className="p-6 md:p-8 rounded-3xl border border-emerald-500/40 bg-white dark:bg-slate-900/90 backdrop-blur-md shadow-2xl text-slate-900 dark:text-white relative overflow-hidden">
      {/* Decorative Glow */}
      <div className="absolute -top-20 -right-20 w-56 h-56 bg-emerald-500/10 rounded-full blur-3xl pointer-events-none" />

      {/* Certificate Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-5 border-b border-slate-200 dark:border-white/10 mb-6">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="w-6 h-6 rounded-md bg-emerald-500 flex items-center justify-center text-white text-xs font-black">CPCB</span>
            <h3 className="font-['Outfit'] font-extrabold text-xl text-slate-900 dark:text-white">
              Verified Recycling Credit Token
            </h3>
          </div>
          <p className="text-xs text-slate-500 dark:text-slate-400">
            Ministry of Environment, Forest and Climate Change (MoEFCC) • National EPR Compliance Registry
          </p>
        </div>
        <span className="px-3.5 py-1.5 rounded-full bg-emerald-500 text-white font-bold text-xs shadow-md shadow-emerald-500/20 tracking-wide uppercase self-start sm:self-auto">
          ✓ Officially Registered
        </span>
      </div>

      {/* Highlight Metrics Banner */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 p-5 rounded-2xl bg-emerald-500/10 border border-emerald-500/25 mb-6">
        <div>
          <span className="text-[10px] uppercase font-bold text-slate-500 dark:text-slate-400 block mb-1">Certified Recycling Volume</span>
          <strong className="font-['Outfit'] text-2xl font-black text-emerald-600 dark:text-emerald-400 block">
            {cert.verified_weight_mt} MT
          </strong>
          <span className="text-xs text-slate-500 dark:text-slate-400">
            ({(cert.listing_weight_kg || cert.verified_weight_mt * 1000).toLocaleString('en-IN')} kg net)
          </span>
        </div>
        <div>
          <span className="text-[10px] uppercase font-bold text-slate-500 dark:text-slate-400 block mb-1">Statutory Material Grade</span>
          <strong className="font-['Outfit'] text-xl font-bold text-slate-900 dark:text-white block mt-0.5">
            {cert.material_grade}
          </strong>
          <span className="text-xs text-slate-500 dark:text-slate-400">CPCB Schedule II Accredited</span>
        </div>
        <div>
          <span className="text-[10px] uppercase font-bold text-slate-500 dark:text-slate-400 block mb-1">Settlement Timestamp</span>
          <strong className="font-['Outfit'] text-base font-bold text-slate-900 dark:text-white block mt-0.5">
            {dateFormatted}
          </strong>
          <span className="text-xs text-slate-500 dark:text-slate-400">{timeFormatted} IST</span>
        </div>
      </div>

      {/* Provenance & Ownership Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
        <div className="p-4 rounded-2xl bg-slate-50 dark:bg-slate-950/60 border border-slate-200 dark:border-white/[0.06]">
          <span className="text-[10px] uppercase font-bold text-slate-500 dark:text-slate-400 block mb-1">Accredited Recycler Facility (Buyer)</span>
          <div className="font-bold text-sm text-slate-900 dark:text-white">{cert.recycler_org || 'Certified Industrial Recycler'}</div>
          <span className="text-xs font-mono text-emerald-600 dark:text-emerald-400 block mt-1">
            Reg: {cert.recycler_cpcb_reg || 'CPCB/EPR/2022/VALID'}
          </span>
        </div>
        <div className="p-4 rounded-2xl bg-slate-50 dark:bg-slate-950/60 border border-slate-200 dark:border-white/[0.06]">
          <span className="text-[10px] uppercase font-bold text-slate-500 dark:text-slate-400 block mb-1">Origin Aggregation Center (Seller)</span>
          <div className="font-bold text-sm text-slate-900 dark:text-white">{cert.seller_org || 'Authorized DWCC Hub'}</div>
          <span className="text-xs font-mono text-sky-600 dark:text-sky-400 block mt-1">
            Traceable Municipal Source
          </span>
        </div>
      </div>

      {/* SHA-256 Ledger Hash Box with 1-Click Copy */}
      <div className="p-4 rounded-2xl bg-slate-100 dark:bg-slate-950 border border-slate-200 dark:border-white/10 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex-1 min-w-0">
          <span className="text-[10px] uppercase font-bold text-slate-500 block mb-0.5">Cryptographic SHA-256 Ledger Hash</span>
          <code className="text-xs font-mono text-cyan-600 dark:text-cyan-400 break-all select-all block">
            {cert.certificate_hash}
          </code>
        </div>
        <button
          type="button"
          onClick={() => onCopyHash(cert.certificate_hash)}
          className="min-h-[44px] px-4 rounded-xl bg-slate-200 dark:bg-slate-800 hover:bg-slate-300 dark:hover:bg-slate-700 text-slate-800 dark:text-white text-xs font-semibold flex items-center justify-center gap-1.5 cursor-pointer whitespace-nowrap self-start sm:self-auto"
        >
          <span>{copied ? '✓ Copied' : '📋 Copy Hash'}</span>
        </button>
      </div>
    </div>
  );
}
